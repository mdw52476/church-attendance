import { useEffect, type ReactNode } from 'react';
import type { AgeGroup, Category } from '../types';
import { ageLabel } from '../types';

export function AgeChip({ age, small }: { age: AgeGroup; small?: boolean }) {
  return <span className={`chip age-${age} ${small ? 'sm' : ''}`}>{ageLabel(age)}</span>;
}

export function CategoryChip({ cat, small, showRegular }: { cat: Category; small?: boolean; showRegular?: boolean }) {
  if (cat === 'regular' && !showRegular) return null;
  const label = cat === 'first_time' ? 'First-time' : cat === 'returning' ? 'Returning' : cat === 'non_regular' ? 'Non-regular' : 'Regular';
  return <span className={`chip cat-${cat} ${small ? 'sm' : ''}`}>{label}</span>;
}

export function SectionBadge({ section }: { section: string }) {
  if (!section) return null;
  return (
    <span className="section-badge" title={`Section ${section}`}>
      {section}
    </span>
  );
}

export function Modal({ title, onClose, children, footer, wide }: { title: string; onClose: () => void; children: ReactNode; footer?: ReactNode; wide?: boolean }) {
  useEffect(() => {
    const k = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', k);
    document.body.classList.add('modal-open');
    return () => {
      window.removeEventListener('keydown', k);
      document.body.classList.remove('modal-open');
    };
  }, [onClose]);
  return (
    <div className="modal-backdrop" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`modal ${wide ? 'wide' : ''}`} role="dialog" aria-label={title}>
        <div className="modal-head">
          <h2>{title}</h2>
          <button className="icon-btn" onClick={onClose} aria-label="Close">
            <Icon name="x" />
          </button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  );
}

export function Segmented<T extends string>({ value, options, onChange }: { value: T; options: { id: T; label: ReactNode }[]; onChange: (v: T) => void }) {
  return (
    <div className="segmented" role="tablist">
      {options.map((o) => (
        <button key={o.id} role="tab" aria-selected={value === o.id} className={value === o.id ? 'on' : ''} onClick={() => onChange(o.id)}>
          {o.label}
        </button>
      ))}
    </div>
  );
}

export function FilterChip({ on, onClick, children, className = '' }: { on: boolean; onClick: () => void; children: ReactNode; className?: string }) {
  return (
    <button className={`filter-chip ${on ? 'on' : ''} ${className}`} aria-pressed={on} onClick={onClick}>
      {children}
    </button>
  );
}

export function SearchBox({ value, onChange, placeholder = 'Search' }: { value: string; onChange: (v: string) => void; placeholder?: string }) {
  return (
    <div className="search">
      <Icon name="search" />
      <input type="search" value={value} placeholder={placeholder} onChange={(e) => onChange(e.target.value)} />
      {value && (
        <button className="icon-btn sm" onClick={() => onChange('')} aria-label="Clear search">
          <Icon name="x" />
        </button>
      )}
    </div>
  );
}

export function Empty({ children }: { children: ReactNode }) {
  return <div className="empty">{children}</div>;
}

